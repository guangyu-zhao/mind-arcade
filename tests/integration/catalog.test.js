import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, access, readdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { games, categories } from '../../src/catalog.js';
import { dictionaries } from '../../src/i18n/translate.js';
import { generatePages } from '../../scripts/pages.mjs';
import { rotationCharacters } from '../../src/games/working-memory/rotation-span/characters.js';
test('database regression cases cover every character generated by rotation span', async () => {
  const sql = await readFile('supabase/tests/rotation-characters.sql', 'utf8');
  const characters = [...sql.match(/from unnest\(array\[([^\]]+)\]/)[1].matchAll(/'([^']+)'/g)].map(
    (match) => match[1],
  );
  assert.deepEqual(characters, rotationCharacters);
});
test('catalog, game entries, names and the database rule registry agree', async () => {
  assert.equal(games.length, 21);
  assert.equal(new Set(games.map((g) => g.id)).size, games.length);
  assert.equal(new Set(games.map((g) => g.route)).size, games.length);
  const sql = await readFile('supabase/migrations/202610170002_current_rules.sql', 'utf8');
  for (const game of games) {
    assert.ok(categories.some((c) => c.id === game.category));
    assert.ok(dictionaries.zh[game.name]);
    assert.notEqual(game.name, game.description);
    assert.ok(dictionaries.en[game.metric.label]);
    assert.ok(sql.includes(`('${game.id}', '${game.version}', '${game.kind}')`), game.id);
    await access(game.assets.entry);
    await access('public/' + game.route + '/favicon.svg');
  }
});
test('generated pages use one shared header, preserve routes and exclude retired history controls', async (t) => {
  const output = await mkdtemp(join(tmpdir(), 'mind-arcade-pages-'));
  t.after(() => rm(output, { recursive: true, force: true }));
  const inputs = await generatePages({ output });
  assert.equal(Object.keys(inputs).length, games.length + 1);
  for (const game of games) {
    const html = await readFile(inputs[game.id], 'utf8');
    assert.ok(html.includes('data-game-id="' + game.id + '"'));
    assert.equal((html.match(/class="site-header"/g) || []).length, 1);
    assert.ok(html.includes('href="../../"'));
    assert.ok(!html.includes('history-panel'));
    assert.ok(!html.includes('import-records'));
  }
  const overview = await readFile(inputs.index, 'utf8');
  assert.equal((overview.match(/class="game-card"/g) || []).length, games.length);
  for (const game of games) assert.ok(overview.includes('./' + game.route + '/'));
});
test('source modules use explicit imports instead of game globals', async () => {
  for (const file of await readdir('src', { recursive: true })) {
    if (!file.endsWith('.js')) continue;
    const text = await readFile('src/' + file, 'utf8');
    assert.doesNotMatch(
      text,
      /window\.(GameCore|MemoryGame|CognitiveGame|MindLabCloud|GameI18n|SpeedGame|SleepGame)/,
      file,
    );
  }
});

test('manually applied migrations stay immutable and are explicitly tracked', async () => {
  const { createHash } = await import('node:crypto');
  const baseline = JSON.parse(await readFile('supabase/manual-baseline.json'));
  assert.equal(baseline.project, 'yjzdcjiuiddhvwmcwmms');
  for (const migration of baseline.migrations) {
    const sql = await readFile('supabase/migrations/' + migration.file);
    assert.equal(createHash('sha256').update(sql).digest('hex'), migration.sha256, migration.file);
  }
  const operations = await readFile('supabase/operations/register-existing-migrations.sql', 'utf8');
  const current = await readFile(
    'supabase/migrations/202610220001_rotation_characters.sql',
    'utf8',
  );
  const body = current.split('as $$')[1].split('$$;')[0];
  const hash = createHash('md5').update(body.replace(/\s/g, '')).digest('hex');
  assert.ok(operations.includes(`('mind_lab_private.level_pass','${hash}')`));
  assert.ok(operations.includes("('202610220001','rotation_characters'"));
});
